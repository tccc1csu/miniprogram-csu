CREATE TABLE jobs(
 task_id TEXT PRIMARY KEY REFERENCES tasks(id), review_mode BOOLEAN NOT NULL DEFAULT false,
 rule_id INTEGER REFERENCES labor_rules(id), complexity TEXT CHECK(complexity IN('basic','complex','large')),
