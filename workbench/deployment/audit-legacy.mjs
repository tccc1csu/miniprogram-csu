import {execFileSync} from 'node:child_process';

const cli=process.argv[2];
if(!cli)throw new Error('Pass the CloudBase CLI bin/tcb JavaScript file');
const environment='cloud1-d2gd4994t925d1435';
const fields={
 departments:['_id'],
 users:['_id','role','department'],
 members:['_id','userId'],
 handoffs:['_id','workflowType','status','submitterMemberId','assigneeMemberId','assignedTime','archivedTime','completedTime'],
 work_item:['_id','member_id','task_id','hours_u','status','source','migrated_from'],
 weekly_records:['_id','memberId','sourceHandoffIds','autoGeneratedWorkload'],
 contribution_basis:['_id','basis_id','member_id','handoff_id'],
 contribution_measurement:['_id','basis_id','base_hours_u'],
 files:['_id','fileID']
};
const names=Object.keys(fields);
function query(commands){
 const output=execFileSync(process.execPath,[cli,'db','nosql','execute','-e',environment,
  '--command',JSON.stringify(commands),'--json'],{encoding:'utf8',windowsHide:true,maxBuffer:16*1024*1024});
 return JSON.parse(output).data.results;
}
const counts=query(names.map(name=>({TableName:name,CommandType:'COMMAND',Command:JSON.stringify({count:name,query:{}})})));
const total=counts.map(([item])=>Number(item.n.$numberInt??item.n.$numberLong??item.n));
const data={};
for(const [index,name] of names.entries()){
 data[name]=[];
 const projection=Object.fromEntries(fields[name].map(key=>[key,1]));
 for(let skip=0;skip<total[index];skip+=100){
  const [page]=query([{TableName:name,CommandType:'QUERY',
   Command:JSON.stringify({find:name,projection,sort:{_id:1},skip,limit:100})}]);
  data[name].push(...page);
 }
 if(data[name].length!==total[index])throw new Error('Source count changed while reading '+name);
}
const idSet=(rows,key='_id')=>new Set(rows.map(row=>row[key]).filter(Boolean));
const users=idSet(data.users),members=idSet(data.members),tasks=idSet(data.handoffs),basis=idSet(data.contribution_basis,'basis_id');
const expectedWorkflows=new Set(['editorialOfficeHandoff','productionReservation','operationsLayout','externalRequest']);
const workflows={};
for(const row of data.handoffs){
 const type=row.workflowType||'editorialOfficeHandoff';
 const label=expectedWorkflows.has(type)?type:'unknown';
 workflows[label]=(workflows[label]||0)+1;
}
const count=(name,test)=>data[name].filter(test).length;
const unit=value=>Number(value?.$numberInt??value?.$numberLong??value?.$numberDouble??value);
console.log(JSON.stringify({
 counts:Object.fromEntries(names.map(name=>[name,data[name].length])),
 workflows,
 review:{
  membersWithoutMatchingAccount:count('members',row=>!users.has(row.userId)),
  handoffsWithUnmatchedMemberReference:count('handoffs',row=>[row.submitterMemberId,row.assigneeMemberId].some(value=>value&&!members.has(value))),
  archivedHandoffsWithoutDate:count('handoffs',row=>row.status==='archived'&&!row.archivedTime&&!row.completedTime),
  workItemsWithoutMatchingMember:count('work_item',row=>!members.has(row.member_id)),
  workItemsWithUnmatchedTask:count('work_item',row=>row.task_id&&!tasks.has(row.task_id)),
  workItemsWithUnusableHours:count('work_item',row=>!Number.isSafeInteger(unit(row.hours_u))||unit(row.hours_u)<=0),
  weeklyRowsWithoutMatchingMember:count('weekly_records',row=>!members.has(row.memberId)),
  weeklyRowsWithAutoHoursAndNoSource:count('weekly_records',row=>unit(row.autoGeneratedWorkload)>0&&!row.sourceHandoffIds?.length),
  measurementsWithoutBasis:count('contribution_measurement',row=>!basis.has(row.basis_id)),
  missingFileReference:count('files',row=>!row.fileID)
 }
},null,2));
