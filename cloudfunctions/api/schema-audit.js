// 仅统计字段和异常数量，不输出姓名、联系方式、令牌或原始业务记录。
function typeOf(value) {
  if (value === null) return 'null'
  if (Array.isArray(value)) return 'array'
  if (value instanceof Date || (value && typeof value === 'object' && '$date' in value)) return 'date'
  return typeof value
}

function inspect(rows) {
  const fields = {}
  rows.forEach(row => Object.keys(row).forEach(name => {
    const type = typeOf(row[name])
    if (!fields[name]) fields[name] = { present: 0, types: {} }
    fields[name].present++
    fields[name].types[type] = (fields[name].types[type] || 0) + 1
  }))
  return { inspected: rows.length, fields }
}

function analyze(collections) {
  const report = { source: 'local-export', collections: {}, issues: {}, scope: 'supplied-collections-only' }
  Object.keys(collections).forEach(name => { report.collections[name] = inspect(collections[name]) })
  const members = collections.members || []
  const departments = collections.departments || []
  const records = collections.weekly_records || []
  function duplicateCount(rows, value) {
    const seen = new Set()
    let count = 0
    rows.forEach(row => {
      const k = value(row)
      if (seen.has(k)) count++
      seen.add(k)
    })
    return count
  }
  function missingRefs(rows, field, targets) {
    const ids = new Set(targets.map(row => row._id))
    return rows.filter(row => row[field] && !ids.has(row[field])).length
  }
  report.issues.duplicate_department_names = duplicateCount(departments, row => row.name)
  report.issues.ambiguous_member_names = duplicateCount(members, row => JSON.stringify([row.department, row.name]))
  report.issues.duplicate_weekly_summaries = duplicateCount(records, row => JSON.stringify([
    row.memberId || row.memberName, row.department, row.week
  ]))
  report.issues.weekly_missing_member_id = records.filter(row => !row.memberId).length
  report.issues.invalid_workload = records.filter(row => row.workload === null || row.workload === '' ||
    !Number.isFinite(Number(row.workload)) || Number(row.workload) < 0).length
  if (collections.members) report.issues.weekly_dangling_member_id = missingRefs(records, 'memberId', members)
  const bases = collections.contribution_basis || []
  const measurements = collections.contribution_measurement || []
  if (collections.members) report.issues.contribution_dangling_member_id = missingRefs(bases, 'member_id', members)
  if (collections.departments) report.issues.contribution_dangling_department_id = missingRefs(bases, 'department_id', departments)
  if (collections.contribution_basis) report.issues.measurement_dangling_basis_id = missingRefs(measurements, 'basis_id', bases)
  if (collections.contribution_policy) report.issues.measurement_dangling_policy_id = missingRefs(measurements, 'policy_id', collections.contribution_policy)
  if (collections.allowance_standard) report.issues.policy_dangling_standard_id = missingRefs(collections.contribution_policy || [], 'standard_id', collections.allowance_standard)
  report.issues.duplicate_contributions = duplicateCount(bases, row => JSON.stringify([row.source_id, row.type_id, row.member_id]))
  report.issues.invalid_measurement_hours = measurements.filter(row => !Number.isSafeInteger(row.base_hours_u) || row.base_hours_u <= 0).length
  report.issues.legacy_auto_records_without_itemized_history = records.filter(row => row.autoGeneratedWorkload &&
    !bases.some(basis => basis.summary_record_id === row._id)).length
  return report
}

module.exports = { inspect, analyze }
