// pages/upload/upload.js - 工作量（部长批量编辑 / 成员上报）
const app = getApp()
const { callFunction } = require('../../utils/db')
const { WORK_TYPES, DEPARTMENT_DEFAULT_WORK_TYPE } = require('../../utils/constants')
const { getCurrentWeek, getRecentWeeks, showToast, showLoading, hideLoading } = require('../../utils/util')

const SORT_MODES = ['default', 'workloadDesc', 'name']
const SORT_OPTIONS = ['按成员顺序', '工时由高到低', '姓名']

Page({
  data: {
    attachmentUploading: false,
    role: '',
    isMember: false,
    department: '',
    workTypeOptions: WORK_TYPES,
    weekList: [],
    weekIndex: 0,
    selectedWeek: '',
    // 腾讯文档式表格交互
    filterMode: 'all',
    sortIndex: 0,
    sortOptions: SORT_OPTIONS,
    selfForm: {
      workContent: '',
      workType: '日常办公',
      workTypeIndex: 3,
      workload: '',
      remark: '',
      attachments: [],
      hasRecord: false
    },
    // 成员列表（含表单数据）
    memberForms: [],   // [{ memberId, memberName, workType, workContent, workload, remark, hasRecord, recordId, status, auto, hidden, saveState }]
    // 汇总
    totalMembers: 0,
    uploadedCount: 0,
    totalWorkload: 0,
    averageWorkload: '0',
    visibleCount: 0,
    submitting: false,
    submitProgress: '',
    exporting: false
  },

  onAttachmentsChange: function (e) { this.setData({ [e.currentTarget.dataset.path]: e.detail.value }) },
  onAttachmentBusy: function (e) {
    this._busyUploads = this._busyUploads || new Set()
    const path = e.currentTarget.dataset.path
    if (e.detail.uploading) this._busyUploads.add(path)
    else this._busyUploads.delete(path)
    this.setData({ attachmentUploading: this._busyUploads.size > 0 })
  },

  onLoad: function (options) {
    if (!app.checkLogin()) return
    const weekList = getRecentWeeks(8)
    const currentWeek = getCurrentWeek()
    const optionWeek = options && options.week ? decodeURIComponent(options.week) : ''
    const selectedWeek = optionWeek || weekList[0] || currentWeek
    let weekIndex = weekList.indexOf(selectedWeek)
    if (weekIndex < 0) {
      weekList.unshift(selectedWeek)
      weekIndex = 0
    }
    this.baseOrder = []
    this.setData({
      role: app.globalData.role,
      isMember: app.globalData.role === 'member',
      department: app.globalData.department,
      weekList: weekList,
      weekIndex: weekIndex,
      selectedWeek: selectedWeek
    })
    this.loadData()
  },

  onShow: function () {
    if (app.globalData.userInfo) {
      this.loadData()
    }
  },

  // 加载成员 + 本周已上传记录
  loadData: function () {
    if (app.globalData.role === 'member') {
      this.loadSelfRecord()
      return
    }

    const { department, selectedWeek } = this.data
    showLoading('加载中...')

    Promise.all([
      callFunction('manageData', { action: 'getMembers', department: department }),
      callFunction('getRecords', { week: selectedWeek, department: department })
    ]).then(([members, records]) => {
      hideLoading()
      // 构建表单数据
      const recordMap = {}
      const legacyRecordMap = {}
      records.forEach(r => {
        if (r.memberId) recordMap[r.memberId] = r
        else legacyRecordMap[r.memberName] = r
      })

      const memberForms = (members || []).map(m => {
        const rec = recordMap[m._id] || legacyRecordMap[m.name]
        const workContent = rec ? rec.workContent : ''
        const workload = rec ? String(rec.workload) : ''
        const workType = rec ? (rec.workType || getDefaultWorkType(department)) : getDefaultWorkType(department)
        return {
          memberId: m._id || '',
          memberName: m.name,
          workType: workType,
          workTypeIndex: getWorkTypeIndex(workType),
          workContent: workContent,
          workload: workload,
          remark: rec ? (rec.remark || '') : '',
          attachments: rec ? (rec.attachments || []) : [],
          hasRecord: !!rec,
          auto: !!(rec && rec.autoGeneratedWorkload),
          recordId: rec ? rec._id : '',
          status: rec ? '已上传' : '待填写',
          hidden: false,
          saveState: rec ? 'saved' : '',
          lastSaved: rec ? JSON.stringify([workType, workContent, workload]) : ''
        }
      })

      this.baseOrder = memberForms.map(f => f.memberName)
      this.setData({ memberForms: memberForms, totalMembers: memberForms.length })
      this.applyView()
    }).catch(err => {
      hideLoading()
      showToast(err.message || '加载失败')
    })
  },

  loadSelfRecord: function () {
    const { selectedWeek } = this.data
    showLoading('加载中...')
    callFunction('getRecords', { week: selectedWeek }).then(records => {
      hideLoading()
      const record = (records || [])[0]
      this.setData({
        selfForm: {
          recordId: record ? record._id : '',
          workType: record ? (record.workType || getDefaultWorkType(app.globalData.department)) : getDefaultWorkType(app.globalData.department),
          workTypeIndex: getWorkTypeIndex(record ? record.workType : getDefaultWorkType(app.globalData.department)),
          workContent: record ? (record.workContent || '') : '',
          workload: record ? String(record.workload || '') : '',
          remark: record ? (record.remark || '') : '',
          attachments: record ? (record.attachments || []) : [],
          hasRecord: !!record
        },
        uploadedCount: record ? 1 : 0,
        totalMembers: 1,
        totalWorkload: record ? String(record.workload || 0) : '0',
      })
    }).catch(err => {
      hideLoading()
      showToast(err.message || '加载失败')
    })
  },

  onWeekChange: function (e) {
    const idx = e.detail.value
    this.setData({
      weekIndex: idx,
      selectedWeek: this.data.weekList[idx]
    })
    this.loadData()
  },

  // ===== 筛选 / 排序（腾讯文档式）=====
  applyView: function () {
    const mode = this.data.filterMode
    const sortMode = SORT_MODES[this.data.sortIndex] || 'default'
    let forms = this.data.memberForms.slice()
    forms.forEach(f => {
      const filled = !!(f.hasRecord || (f.workContent && f.workContent.trim()))
      f.hidden = (mode === 'done' && !filled) || (mode === 'pending' && filled)
    })
    if (sortMode === 'workloadDesc') {
      forms.sort((a, b) => (parseFloat(b.workload) || 0) - (parseFloat(a.workload) || 0))
    } else if (sortMode === 'name') {
      forms.sort((a, b) => String(a.memberName).localeCompare(String(b.memberName), 'zh'))
    } else if (this.baseOrder && this.baseOrder.length) {
      const order = {}
      this.baseOrder.forEach((name, i) => { order[name] = i })
      forms.sort((a, b) => {
        const ia = order[a.memberName] === undefined ? 1e9 : order[a.memberName]
        const ib = order[b.memberName] === undefined ? 1e9 : order[b.memberName]
        return ia - ib
      })
    }
    this.setData({ memberForms: forms })
    this.updateSummary(forms)
  },

  switchFilter: function (e) {
    const filter = e.currentTarget.dataset.filter
    if (filter === this.data.filterMode) return
    this.setData({ filterMode: filter })
    this.applyView()
  },

  onSortChange: function (e) {
    const idx = Number(e.detail.value) || 0
    this.setData({ sortIndex: idx })
    this.applyView()
  },

  // 更新汇总数据
  updateSummary: function (forms) {
    const list = forms || this.data.memberForms
    let uploaded = 0, workload = 0, visible = 0
    list.forEach(f => {
      if (f.hasRecord || (f.workContent && f.workContent.trim())) uploaded++
      workload += parseFloat(f.workload) || 0
      if (!f.hidden) visible++
    })
    const total = this.data.totalMembers || list.length || 1
    this.setData({
      uploadedCount: uploaded,
      totalWorkload: workload.toFixed(1),
      averageWorkload: (workload / total).toFixed(1),
      visibleCount: visible
    })
  },

  // ===== 输入处理 =====
  onContentInput: function (e) {
    const idx = e.currentTarget.dataset.index
    const val = e.detail.value
    const forms = this.data.memberForms
    forms[idx].workContent = val
    forms[idx].status = val ? '已填写' : '待填写'
    forms[idx].saveState = ''
    this.setData({ memberForms: forms })
    this.updateSummary(forms)
  },

  onWorkTypeChange: function (e) {
    const idx = e.currentTarget.dataset.index
    const typeIndex = Number(e.detail.value) || 0
    const forms = this.data.memberForms
    forms[idx].workTypeIndex = typeIndex
    forms[idx].workType = this.data.workTypeOptions[typeIndex]
    forms[idx].saveState = ''
    this.setData({ memberForms: forms })
    this.autoSaveRow(idx)
  },

  onWorkloadInput: function (e) {
    const idx = e.currentTarget.dataset.index
    let val = e.detail.value.replace(/[^\d.]/g, '')
    const forms = this.data.memberForms
    forms[idx].workload = val
    forms[idx].saveState = ''
    this.setData({ memberForms: forms })
    this.updateSummary(forms)
  },

  onRemarkInput: function (e) {
    const idx = e.currentTarget.dataset.index
    const forms = this.data.memberForms
    forms[idx].remark = e.detail.value
    this.setData({ memberForms: forms })
  },

  // 失焦即自动保存（腾讯文档手感）
  onContentBlur: function (e) {
    this.autoSaveRow(e.currentTarget.dataset.index)
  },

  onWorkloadBlur: function (e) {
    this.autoSaveRow(e.currentTarget.dataset.index)
  },

  autoSaveRow: function (idx) {
    const form = this.data.memberForms[idx]
    if (!form) return
    const content = String(form.workContent || '').trim()
    const workload = String(form.workload === undefined || form.workload === null ? '' : form.workload).trim()
    // 未填完整的不自动保存，交由批量提交兜底。
    if (!content || workload === '') return
    const snapshot = JSON.stringify([form.workType, form.workContent, workload])
    if (form.hasRecord && form.lastSaved === snapshot) return

    this.setData({ ['memberForms[' + idx + '].saveState']: 'saving' })
    callFunction('addRecord', {
      memberId: form.memberId,
      memberName: form.memberName,
      department: this.data.department,
      week: this.data.selectedWeek,
      workType: form.workType || getDefaultWorkType(this.data.department),
      workContent: content,
      workload: parseFloat(workload) || 0,
      remark: String(form.remark || '').trim(),
      attachments: form.attachments || [],
      uploadedBy: app.globalData.userInfo.name
    }).then(() => {
      this.setData({
        ['memberForms[' + idx + '].hasRecord']: true,
        ['memberForms[' + idx + '].status']: '已上传',
        ['memberForms[' + idx + '].saveState']: 'saved',
        ['memberForms[' + idx + '].lastSaved']: snapshot
      })
      this.updateSummary(this.data.memberForms)
    }).catch(err => {
      this.setData({ ['memberForms[' + idx + '].saveState']: 'error' })
      showToast(err.message || '保存失败')
    })
  },

  onSelfContentInput: function (e) {
    this.setData({ 'selfForm.workContent': e.detail.value })
  },

  onSelfWorkTypeChange: function (e) {
    const typeIndex = Number(e.detail.value) || 0
    this.setData({
      'selfForm.workTypeIndex': typeIndex,
      'selfForm.workType': this.data.workTypeOptions[typeIndex]
    })
  },

  onSelfWorkloadInput: function (e) {
    this.setData({ 'selfForm.workload': e.detail.value.replace(/[^\d.]/g, '') })
  },

  onSelfRemarkInput: function (e) {
    this.setData({ 'selfForm.remark': e.detail.value })
  },

  handleSelfSubmit: function () {
    if (this.data.submitting || this.data.attachmentUploading) { showToast('请等待附件上传完成'); return }
    const { selfForm, selectedWeek } = this.data
    if (!selfForm.workContent.trim()) {
      showToast('请填写工作内容')
      return
    }
    if (!String(selfForm.workload).trim()) {
      showToast('请填写工时')
      return
    }

    this.setData({ submitting: true })
    showLoading('提交中...')
    callFunction('addRecord', {
      week: selectedWeek,
      workType: selfForm.workType || getDefaultWorkType(app.globalData.department),
      workContent: selfForm.workContent.trim(),
      workload: parseFloat(selfForm.workload) || 0,
      remark: selfForm.remark.trim(), attachments: selfForm.attachments || []
    }).then(() => {
      hideLoading()
      showToast('上报成功', 'success')
      this.setData({ submitting: false })
      this.loadSelfRecord()
    }).catch(err => {
      hideLoading()
      showToast(err.message || '提交失败')
      this.setData({ submitting: false })
    })
  },

  // 批量提交（兜底：一键提交所有已填写的成员）
  handleBatchSubmit: function () {
    if (this.data.submitting || this.data.attachmentUploading) { showToast('请等待附件上传完成'); return }
    const { memberForms, selectedWeek, department } = this.data
    const validForms = memberForms.filter(f => f.workContent.trim() && f.workload !== '')

    if (validForms.length === 0) {
      showToast('请至少填写一位成员的工作内容')
      return
    }

    this.setData({ submitting: true, submitProgress: '0/' + validForms.length })
    showLoading('提交中 0/' + validForms.length)

    let completed = 0
    const total = validForms.length
    const that = this

    function submitNext() {
      if (completed >= total) {
        hideLoading()
        showToast('批量提交成功', 'success')
        that.setData({ submitting: false, submitProgress: '' })
        that.loadData()
        return
      }

      const f = validForms[completed]
      that.setData({ submitProgress: (completed + 1) + '/' + total })
      showLoading('提交中 ' + (completed + 1) + '/' + total)

      callFunction('addRecord', {
        memberId: f.memberId,
        memberName: f.memberName,
        department: department,
        week: selectedWeek,
        workType: f.workType || getDefaultWorkType(department),
        workContent: f.workContent.trim(),
        workload: parseFloat(f.workload) || 0,
        remark: f.remark.trim(), attachments: f.attachments || [],
        uploadedBy: app.globalData.userInfo.name
      }).then(() => {
        completed++
        submitNext()
      }).catch(err => {
        completed++
        console.error('提交失败:', f.memberName, err)
        submitNext()
      })
    }

    submitNext()
  },

  // 一键导出当前周工作量明细（CSV）
  handleExport: function () {
    const { memberForms, selectedWeek, department } = this.data
    const rows = memberForms.filter(f => (f.workContent && f.workContent.trim()) || f.workload !== '')
    if (rows.length === 0) {
      showToast('暂无可导出的数据')
      return
    }
    const header = ['成员', '部门', '工作类型', '工作内容', '工时(h)', '来源'].map(csvCell).join(',')
    const lines = rows.map(f => [
      f.memberName,
      department,
      f.workType,
      String(f.workContent || '').replace(/[\r\n]+/g, ' '),
      parseFloat(f.workload) || 0,
      f.auto ? '归档自动核算' : (f.hasRecord ? '手动填写' : '未保存')
    ].map(csvCell).join(','))
    const csv = '\ufeff' + [header].concat(lines).join('\r\n')
    const fileName = (selectedWeek || '工作量') + '_工作量明细.csv'

    const fallback = () => {
      wx.setClipboardData({
        data: csv,
        success: () => showToast('已复制到剪贴板', 'success')
      })
    }
    if (!wx.getFileSystemManager || !wx.env || !wx.env.USER_DATA_PATH) {
      fallback()
      return
    }
    this.setData({ exporting: true })
    try {
      const filePath = wx.env.USER_DATA_PATH + '/' + fileName
      wx.getFileSystemManager().writeFile({
        filePath: filePath,
        data: csv,
        encoding: 'utf8',
        success: () => {
          this.setData({ exporting: false })
          if (!wx.shareFileMessage) { fallback(); return }
          wx.shareFileMessage({
            filePath: filePath,
            fileName: fileName,
            success: () => showToast('已导出', 'success'),
            fail: () => fallback()
          })
        },
        fail: () => { this.setData({ exporting: false }); fallback() }
      })
    } catch (e) {
      this.setData({ exporting: false })
      fallback()
    }
  },

  // 一键清空本周数据
  handleClearWeek: function () {
    const that = this
    const department = this.data.department
    wx.showModal({
      title: '确认清空',
      content: '确定要清空本周所有已填写的数据吗？此操作不会删除已提交到服务器的记录。',
      confirmColor: '#E74C3C',
      success: function (res) {
        if (res.confirm) {
          const forms = that.data.memberForms.map(f => ({
            ...f,
            workType: f.workType || getDefaultWorkType(department),
            workTypeIndex: getWorkTypeIndex(f.workType || getDefaultWorkType(department)),
            workContent: '',
            workload: '',
            remark: '',
            status: '待填写',
            saveState: '',
            lastSaved: ''
          }))
          that.setData({ memberForms: forms })
          that.updateSummary(forms)
          showToast('已清空')
        }
      }
    })
  },

})

function getDefaultWorkType(department) {
  return DEPARTMENT_DEFAULT_WORK_TYPE[department] || '日常办公'
}

function getWorkTypeIndex(type) {
  const index = WORK_TYPES.indexOf(type)
  return index >= 0 ? index : WORK_TYPES.indexOf('日常办公')
}

function csvCell(value) {
  const text = String(value === undefined || value === null ? '' : value)
  return '"' + text.replace(/"/g, '""') + '"'
}
