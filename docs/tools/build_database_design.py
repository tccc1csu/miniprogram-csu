for name in names:
    info=list(db.execute(f'PRAGMA table_info({name})'))
    if name.startswith('v_'):continue
    fks=[]
    for row in db.execute(f'PRAGMA foreign_key_list({name})'):
        fid,seq,target,col,to,*_=row
        fks.append(dict(id=fid,seq=seq,target=target,col=col,to=to))
    uniques=[]
    for idx in db.execute(f'PRAGMA index_list({name})'):
        if idx[2]:uniques.append(dict(name=idx[1],columns=[x[2] for x in db.execute(f'PRAGMA index_info({idx[1]})')],partial=bool(idx[4])))
    tables[name]=dict(name=name,label=names[name],columns=[dict(cid=r[0],name=r[1],type=r[2],nullable=not(r[3] or r[5]),default=r[4],pk=r[5]) for r in info],fks=fks,uniques=uniques)

